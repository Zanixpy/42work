#include "../../include/utils.h"

int is_space_tabs_null(char *s)
{
    if (!s)
        return (TRUE);
    while (*s) 
    {
        if (*s != ' ' || *s != '\t')
            return (FALSE);
        s++;
    }
    return (TRUE);
}

